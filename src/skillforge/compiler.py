import json

class SkillCompiler:
    @staticmethod
    def compile_from_spec(spec_file: str) -> str:
        with open(spec_file, "r", encoding="utf-8") as f:
            data = json.load(f)
        title = data.get("info", {}).get("title", "GeneratedSkill")
        class_name = "".join(x.capitalize() for x in title.split())
        return f'''# Auto-generated by SkillForge v1.0.0
class {class_name}Skill:
    name = "{title.lower()}"
    def execute(self, **kwargs):
        print(f"Executing {{self.name}} with parameters: {{kwargs}}")
        return {{"status": "success", "data": kwargs}}
'''
